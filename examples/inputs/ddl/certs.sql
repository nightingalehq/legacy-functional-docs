CREATE TABLE MILL_CERT (
  CERT_NO      CHAR(12) NOT NULL,
  HEAT_NO      CHAR(10) NOT NULL,
  CAST_DATE    DATE,
  GRADE_CODE   CHAR(6) NOT NULL,
  YIELD_MPA    DECIMAL(7,2),
  PRIMARY KEY (CERT_NO),
  FOREIGN KEY (GRADE_CODE) REFERENCES GRADE_MASTER
) IN STEELDB.TSCERT;
CREATE UNIQUE INDEX XCERT1 ON MILL_CERT (CERT_NO);
CREATE TABLE GRADE_MASTER (
  GRADE_CODE  CHAR(6) NOT NULL,
  DESCRIPTION VARCHAR(40),
  PRIMARY KEY (GRADE_CODE)
);
